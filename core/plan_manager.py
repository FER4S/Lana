REFERRAL_DRAFT: str = "draft"
REFERRAL_NOTE: str = "note"
REFERRAL_UNCLEAR: str = "unclear"

# ── Draft plan-type verdicts ─────────────────────────────────────────────────
PLAN_TYPE_STANDARD: str = "standard"
PLAN_TYPE_UNIQUE: str = "unique"

# How squarely a referral flag matched. Presentational only — see the comment
# in _coerce_screening. Never used to decide whether a referral is raised.
CONFIDENCE_CONFIDENT: str = "confident"
CONFIDENCE_POSSIBLE: str = "possible"

# The seven timing columns of her supplement table, in her order. Keys are the
