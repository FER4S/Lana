# ─────────────────────────────────────────────────────────────────────────────
#  core/plan_manager.py – Treatment plan drafting for Lana
#  Screens a dictated patient case against Alexandra's documented referral
#  criteria, drafts a phased plan grounded only in her documents, checks that
#  draft back against her contraindication rules, and renders a markdown file
#  for her review.
#
#  INVARIANT — THIS MODULE HAS NO DELIVERY PATH.
#  Its only side effect is writing a markdown file under data/treatment_plans/.
#  It imports no transport (smtplib, email_send, the Gmail API) and must never
#  gain one. Unlike the email send flow there is no irreversible act here, so
#  the catastrophic failures are content failures — a missed referral, an
#  unflagged contraindication, a silent guess where her documents are silent —
#  and that is where the engineering concentrates:
#
#    * No screening → no draft, ever (screen_case failing is fail-closed).
#    * Every drafted item cites a source; uncited items are flagged in Python,
#      not trusted.
#    * Every cited rule id is checked against the real rulebook, so a
#      hallucinated citation is caught deterministically.
#    * The DRAFT banner and her standing patient instructions are emitted by
#      the renderer, never generated by a model.
# ─────────────────────────────────────────────────────────────────────────────

