    def _render_supplement_table(self, w, items, title: str) -> None:
        if not items:
            return
        w(f"### {title}")
        w("")
        headers = ["Supplement", "Purpose", "Frequency"] + [c for _, c in _TIMING_COLUMNS] + ["Comments"]
        w("| " + " | ".join(headers) + " |")
        w("| " + " | ".join(["---"] * len(headers)) + " |")
        for item in items:
            if not isinstance(item, dict):
                continue
            timing = item.get("timing") or {}
            row = [
                self._cell(item.get("product", "")),
                self._cell(item.get("purpose", "")),
                self._cell(item.get("frequency", "")),
            ]
            row += [self._cell(timing.get(key, "")) for key, _ in _TIMING_COLUMNS]
            row.append(self._cell(item.get("comments", "")))
            w("| " + " | ".join(row) + " |")
        w("")

    def _render_simple_table(self, w, items, title: str, header: str, key: str) -> None:
        if not items:
            return
        w(f"### {title}")
        w("")
        w(f"| {header} | Purpose | Frequency | Comments |")
        w("| --- | --- | --- | --- |")
        for item in items:
            if not isinstance(item, dict):
                continue
            w("| " + " | ".join([
                self._cell(item.get(key, "")),
                self._cell(item.get("purpose", "")),
                self._cell(item.get("frequency", "")),
                self._cell(item.get("comments", "")),
            ]) + " |")
        w("")

    @staticmethod
    def _cell(value) -> str:
        """Make a value safe inside a markdown table cell."""
        text = str(value if value is not None else "").strip()
        return text.replace("|", "\\|").replace("\n", " ")

    @staticmethod
    def _slugify(text: str) -> str:
        """
        Filename-safe patient label. Deliberately short — data/ syncs to
        OneDrive, so a first name or initials is all that should be in a
        filename.
        """
        slug = re.sub(r"[^a-zA-Z0-9]+", "-", str(text or "patient")).strip("-").lower()
        return (slug or "patient")[:24]

    @staticmethod
    def _opt_str(value) -> str | None:
        return value.strip() if isinstance(value, str) and value.strip() else None

    @staticmethod
    def _str_list(value) -> list[str]:
        if not isinstance(value, list):
            return []
        return [str(v).strip() for v in value if str(v).strip()]

    def _render_applicable_rules(self, rule_ids: list[str]) -> str:
        """Render the subset of rules in force for this patient, for a prompt."""
        lines = []
        for rule_id in rule_ids:
            rule = self._knowledge.rule(rule_id)
            if not rule:
                continue
            restricted = "; ".join(
                f"{item.get('item', '')} → {item.get('action', '')}"
                + (f" (limit {item['limit']})" if item.get("limit") else "")
                + (f" [{item['note']}]" if item.get("note") else "")
                for item in rule.get("restricted", [])
            )
            lines.append(
                f"[{rule_id}] {restricted}\n"
                f"    her words: \"{rule['verbatim']}\""
            )
        return "\n".join(lines)

    @staticmethod
    def _extract_draft_items(draft: dict) -> str:
        """Flatten the drafted items into the list the checker reasons over."""
        lines = []
        for phase in draft.get("phases") or []:
            phase_name = str(phase.get("name", "Phase"))
            for bucket, key in (("supplements", "product"), ("keep_supplements", "product"),
                                ("food_therapy", "food"), ("lifestyle_therapy", "lifestyle")):
                for item in phase.get(bucket) or []:
                    if not isinstance(item, dict):
                        continue
                    timing = item.get("timing") or {}
                    when = ", ".join(
                        f"{label} {timing[key_]}" for key_, label in _TIMING_COLUMNS
                        if str(timing.get(key_, "")).strip()
                    )
                    lines.append(
                        f"- [{phase_name}] {item.get(key, '?')} — "
                        f"{item.get('frequency', '')} {when} — {item.get('comments', '')}"
                    )
        return "\n".join(lines)

    @staticmethod
    def _compact_draft_for_revision(draft: dict) -> str:
        """A compact view of a prior draft, so the revise call edits rather than restarts."""
        lines = []
        for phase in draft.get("phases") or []:
            lines.append(f"{phase.get('name', 'Phase')} ({phase.get('duration_weeks', '?')} weeks)")
            for bucket, key in (("supplements", "product"), ("keep_supplements", "product"),
                                ("food_therapy", "food"), ("lifestyle_therapy", "lifestyle")):
                for item in phase.get(bucket) or []:
                    if isinstance(item, dict):
                        lines.append(
                            f"  - [{bucket}] {item.get(key, '?')}: "
                            f"{item.get('frequency', '')} — {item.get('purpose', '')}"
                        )
        return "\n".join(lines)

    @staticmethod
    def _log_cache_usage(response, label: str) -> None:
        """
        Log prompt-cache hits. The pinned anthropic==0.40.0 predates GA
        caching in its non-beta types, so whether cache_control survives to the
        wire is verified rather than assumed — this is where the evidence shows
        up. Never fatal: caching is a cost optimization, not correctness.
        """
        usage = getattr(response, "usage", None)
        if usage is None:
            return
        written = getattr(usage, "cache_creation_input_tokens", None)
        read = getattr(usage, "cache_read_input_tokens", None)
        if written or read:
            logger.debug(f"{label}: cache write={written} read={read}")


